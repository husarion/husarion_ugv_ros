// The limited master.dcf is generated by dcfgen. This catches a canopen_configuration.yaml edit
// that was not regenerated into one of the two files, and a regeneration that changed more than
// the objects the limited configuration is meant to change.

namespace
{

using Section = std::map<std::string, std::string>;
using DCF = std::map<std::string, Section>;

DCF ReadDCF(const std::string & path)
{
  std::ifstream file(path);
  EXPECT_TRUE(file.good()) << "Can't read " << path;

  DCF dcf;
  Section * section = nullptr;
  std::string line;
  while (std::getline(file, line)) {
    line.erase(std::remove(line.begin(), line.end(), '\r'), line.end());
    if (line.empty() || line.front() == ';') {
      continue;
    }
    if (line.front() == '[' && line.back() == ']') {
      section = &dcf[line.substr(1, line.size() - 2)];
    } else if (section && line.find('=') != std::string::npos) {
      const auto eq = line.find('=');
      (*section)[line.substr(0, eq)] = line.substr(eq + 1);
    }
  }
  return dcf;
}

// Sections of the objects the limited configuration adds or changes on purpose.
bool IsExpectedDifference(const std::string & name)
{
  return name.rfind("1012", 0) == 0 || name.rfind("1013", 0) == 0 || name.rfind("1F22", 0) == 0 ||
         name == "1F81Value";
}

std::set<std::string> ObjectList(const Section & section)
{
  std::set<std::string> objects;
  for (const auto & [key, value] : section) {
    if (key != "SupportedObjects") {
      objects.insert(value);
    }
  }
  return objects;
}

}  // namespace

TEST(TestLimitedTPDORatesDCF, DiffersFromStockOnlyInExpectedObjects)
{
  const auto stock = ReadDCF(std::string(DCF_CONFIG_DIR) + "/master.dcf");
  const auto limited = ReadDCF(std::string(DCF_CONFIG_DIR) + "/limited_tpdo_rates/master.dcf");
  ASSERT_FALSE(stock.empty());
  ASSERT_FALSE(limited.empty());

  std::set<std::string> names;
  for (const auto & [name, section] : stock) {
    names.insert(name);
  }
  for (const auto & [name, section] : limited) {
    names.insert(name);
  }

  for (const auto & name : names) {
    if (IsExpectedDifference(name)) {
      continue;
    }
    const auto in_stock = stock.find(name);
    const auto in_limited = limited.find(name);
    ASSERT_TRUE(in_stock != stock.end()) << "[" << name << "] only in the limited DCF";
    ASSERT_TRUE(in_limited != limited.end()) << "[" << name << "] only in the stock DCF";

    if (name == "OptionalObjects") {
      auto limited_objects = ObjectList(in_limited->second);
      for (const auto & added : {"0x1012", "0x1013", "0x1F22"}) {
        EXPECT_EQ(limited_objects.erase(added), 1u) << added << " missing in the limited DCF";
      }
      EXPECT_EQ(ObjectList(in_stock->second), limited_objects);
      continue;
    }
    EXPECT_EQ(in_stock->second, in_limited->second) << "[" << name << "] differs";
  }

  // Bits 8-15 add a life time factor, which lely does not use for a slave whose heartbeat it
  // consumes. The boot bits stay as in the stock file.
  const auto & slave_assignment = limited.at("1F81Value");
  EXPECT_EQ(slave_assignment.at("1"), "0x00000305");
  EXPECT_EQ(slave_assignment.at("2"), "0x00000305");
  EXPECT_EQ(stock.at("1F81Value").at("1"), "0x00000005");
}

